class Timer:
    """Context manager for timing code execution.
    
    Provides easy timing of code blocks with automatic logging.
    
    Example:
        >>> with Timer(logger, "Checkpoint loading"):
        ...     load_checkpoints()
    """
    
    def __init__(self, logger: logging.Logger, operation: str):
        """Initialize timer.
        
        Args:
            logger: Logger instance for output
            operation: Description of the operation being timed
        """
        self.logger = logger
        self.operation = operation
        self.start_time = None
        self.end_time = None
    
    def __enter__(self):
        """Start timing."""
        self.start_time = time.time()
        self.logger.info(f"Starting: {self.operation}")
        return self
    
    def __exit__(self, exc_type, exc_val, exc_tb):
        """End timing and log elapsed time."""
        self.end_time = time.time()
        elapsed = self.end_time - self.start_time
        self.logger.info(f"Completed: {self.operation} (took {elapsed:.2f}s)")
        return False  # Don't suppress exceptions
    
    def elapsed(self) -> float:
        """Get elapsed time in seconds.
        
        Returns:
            Elapsed time in seconds, or 0 if timer not started
        """
        if self.start_time is None:
            return 0.0
        end = self.end_time if self.end_time is not None else time.time()
        return end - self.start_time


