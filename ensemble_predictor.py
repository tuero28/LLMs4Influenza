def weighted_average(
    predictions: List[torch.Tensor],
    weights: List[float]
) -> torch.Tensor:
    """Compute weighted average of prediction tensors.
    
    Combines multiple prediction tensors using weighted averaging. All tensors
    must have identical shapes, and weights must sum to 1.0.
    
    Args:
        predictions: List of prediction tensors (all must have same shape)
        weights: List of weights (must sum to 1.0, same length as predictions)
        
    Returns:
        Ensemble prediction tensor (weighted average)
        
    Raises:
        ValueError: If predictions have different shapes
        ValueError: If predictions and weights have different lengths
        ValueError: If weights don't sum to 1.0 (within tolerance)
        
    Examples:
        >>> pred1 = torch.randn(32, 8, 1)  # [batch, pred_len, features]
        >>> pred2 = torch.randn(32, 8, 1)
        >>> pred3 = torch.randn(32, 8, 1)
        >>> weights = [0.3, 0.3, 0.4]
        >>> ensemble = weighted_average([pred1, pred2, pred3], weights)
        >>> ensemble.shape
        torch.Size([32, 8, 1])
        
    **Validates: Requirement 3.2**
    
    Implementation Notes:
        - Validates all tensors have identical shapes
        - Validates weights sum to 1.0 within tolerance
        - Uses element-wise multiplication and sum for numerical stability
        - Result tensor is on same device as input tensors
    """
    # Validate inputs
    if len(predictions) == 0:
        raise ValueError("Cannot compute weighted average of empty prediction list")
    
    if len(predictions) != len(weights):
        raise ValueError(
            f"Number of predictions ({len(predictions)}) must match number of weights ({len(weights)})"
        )
    
    # Validate weights sum to 1.0
    weight_sum = sum(weights)
    if abs(weight_sum - 1.0) > WEIGHT_SUM_TOLERANCE:
        raise ValueError(
            f"Weights must sum to 1.0 (got {weight_sum:.6f}). "
            f"Use normalize_weights() to fix this."
        )
    
    # Validate all predictions have same shape
    reference_shape = predictions[0].shape
    for i, pred in enumerate(predictions[1:], start=1):
        if pred.shape != reference_shape:
            raise ValueError(
                f"All predictions must have identical shapes. "
                f"Prediction 0 has shape {reference_shape}, "
                f"but prediction {i} has shape {pred.shape}"
            )
    
    # Compute weighted average: sum(w_i * pred_i)
    ensemble = torch.zeros_like(predictions[0])
    for weight, pred in zip(weights, predictions):
        ensemble += weight * pred
    
    return ensemble


