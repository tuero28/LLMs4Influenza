@dataclass
class EnsembleMetrics:
    """Container for ensemble performance metrics.
    
    Stores metrics for individual models and the ensemble, along with
    improvement percentages to quantify ensemble performance gains.
    
    Attributes:
        ensemble_mse: Mean Squared Error for ensemble predictions
        ensemble_mae: Mean Absolute Error for ensemble predictions
        dlinear_mse: MSE for DLinear model (if available)
        dlinear_mae: MAE for DLinear model (if available)
        patchtst_mse: MSE for PatchTST model (if available)
        patchtst_mae: MAE for PatchTST model (if available)
        llama2_mse: MSE for Llama2 model (if available)
        llama2_mae: MAE for Llama2 model (if available)
        mse_improvement: Dict of MSE improvement percentages vs each model
        mae_improvement: Dict of MAE improvement percentages vs each model
        
    Example:
        >>> metrics = EnsembleMetrics(
        ...     ensemble_mse=0.045, ensemble_mae=0.15,
        ...     dlinear_mse=0.052, dlinear_mae=0.17
        ... )
        >>> metrics.mse_improvement['DLinear'] = 13.5
        
    **Validates: Requirements 6.1, 6.2, 6.3, 6.4**
    """
    
    # Ensemble metrics
    ensemble_mse: float = 0.0
    ensemble_mae: float = 0.0
    
    # Individual model metrics (optional)
    dlinear_mse: Optional[float] = None
    dlinear_mae: Optional[float] = None
    patchtst_mse: Optional[float] = None
    patchtst_mae: Optional[float] = None
    llama2_mse: Optional[float] = None
    llama2_mae: Optional[float] = None
    
    # Improvement percentages
    mse_improvement: Dict[str, float] = field(default_factory=dict)
    mae_improvement: Dict[str, float] = field(default_factory=dict)


def compute_improvement_percentage(baseline: float, improved: float) -> float:
    """Calculate percentage improvement from baseline to improved metric.
    
    Uses the formula: ((baseline - improved) / baseline) * 100
    Positive values indicate improvement (lower is better for MSE/MAE).
    
    Args:
        baseline: Baseline metric value (e.g., individual model MSE)
        improved: Improved metric value (e.g., ensemble MSE)
        
    Returns:
        Percentage improvement (positive = better, negative = worse)
        
    Raises:
        ValueError: If baseline is zero (division by zero)
        
    Examples:
        >>> compute_improvement_percentage(0.050, 0.045)
        10.0  # 10% improvement
        
        >>> compute_improvement_percentage(0.050, 0.055)
        -10.0  # 10% worse
        
        >>> compute_improvement_percentage(0.050, 0.050)
        0.0  # No change
        
    **Validates: Requirement 6.4**
    
    Implementation Notes:
        - Handles division by zero with epsilon fallback
        - Returns 0.0 for zero baseline (edge case)
        - Preserves sign: positive = improvement, negative = degradation
    """
    if baseline == 0.0:
        # Edge case: avoid division by zero
        logger.warning("Baseline metric is zero, cannot compute improvement percentage")
        return 0.0
    
    # Calculate improvement: positive values mean improved performance
    improvement = ((baseline - improved) / baseline) * 100.0
    
    return improvement


