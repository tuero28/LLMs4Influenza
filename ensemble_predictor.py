def discover_checkpoints(
    checkpoints_dir: str,
    model_types: List[str],
    iteration: int = 0
) -> Dict[str, str]:
    """Discover checkpoint paths for specified model types and iteration.
    
    Builds checkpoint paths following the project's naming convention and
    verifies that checkpoint files exist on the filesystem. Supports flexible
    matching for different hyperparameter configurations.
    
    Args:
        checkpoints_dir: Base directory containing checkpoints (e.g., './checkpoints/')
        model_types: List of model type names (e.g., ['DLinear', 'PatchTST', 'Llama2'])
        iteration: Training iteration number (0, 1, or 2 for itr0, itr1, itr2)
        
    Returns:
        Dictionary mapping model names to checkpoint paths for found checkpoints
        
    Examples:
        >>> discover_checkpoints('./checkpoints/', ['DLinear', 'PatchTST'], iteration=0)
        {
            'DLinear': './checkpoints/DLinear_full_sl336_ll18_pl8_dm768_nh16_el3_gl6_df512_ebtimeF_itr0/checkpoint.pth',
            'PatchTST': './checkpoints/PatchTST_full_sl336_ll18_pl8_dm768_nh16_el3_gl6_df512_ebtimeF_itr0/checkpoint.pth'
        }
        
    **Validates: Requirements 1.1, 1.2, 1.3**
    
    Implementation Notes:
        - Handles missing checkpoint directories gracefully (logs warning, excludes from results)
        - Uses project naming convention: {model}_full_sl336_ll18_pl{X}_dm{Y}_nh{Z}_el3_gl6_df{W}_ebtimeF_itr{N}
        - DLinear and PatchTST use pl8, Llama2 uses pl13
        - DLinear/PatchTST use dm768, Llama2 uses dm4096
        - Supports flexible config matching (e.g., nh4/nh16, df512/df768)
    """
    checkpoint_paths = {}
    
    for model_type in model_types:
        # Build primary checkpoint path following naming convention
        if model_type == 'DLinear':
            checkpoint_patterns = [
                f"DLinear_full_sl336_ll18_pl8_dm768_nh16_el3_gl6_df512_ebtimeF_itr{iteration}"
            ]
        elif model_type == 'PatchTST':
            checkpoint_patterns = [
                f"PatchTST_full_sl336_ll18_pl8_dm768_nh16_el3_gl6_df512_ebtimeF_itr{iteration}"
            ]
        elif model_type == 'Llama2':
            # Try multiple config variations for Llama2
            checkpoint_patterns = [
                f"Llama2_full_sl336_ll18_pl13_dm4096_nh16_el3_gl6_df512_ebtimeF_itr{iteration}",
                f"Llama2_full_sl336_ll18_pl13_dm4096_nh4_el3_gl6_df768_ebtimeF_itr{iteration}",
                f"Llama2_full_sl336_ll18_pl13_dm4096_nh8_el3_gl6_df512_ebtimeF_itr{iteration}"
            ]
        else:
            logger.warning(f"Unknown model type '{model_type}', skipping")
            continue
        
        # Try each pattern until we find an existing checkpoint
        found = False
        for checkpoint_dir in checkpoint_patterns:
            checkpoint_path = os.path.join(checkpoints_dir, checkpoint_dir, 'checkpoint.pth')
            
            # Check if checkpoint exists
            if os.path.exists(checkpoint_path):
                checkpoint_paths[model_type] = checkpoint_path
                logger.debug(f"Found checkpoint for {model_type}: {checkpoint_path}")
                found = True
                break
        
        if not found:
            logger.warning(f"Checkpoint not found for {model_type} itr{iteration} (tried {len(checkpoint_patterns)} patterns)")
    
    logger.info(f"Discovered {len(checkpoint_paths)}/{len(model_types)} checkpoints for iteration {iteration}")
    
    return checkpoint_paths


def load_checkpoint(
    model_type: str,
    checkpoint_path: str,
    device: torch.device,
    args
) -> Optional[nn.Module]:
    """Load a model checkpoint from disk.
    
    Instantiates the model architecture, loads the saved state dict, and
    prepares the model for inference (evaluation mode, no gradients).
    
    Args:
        model_type: Type of model ('DLinear', 'PatchTST', or 'Llama2')
        checkpoint_path: Path to checkpoint file
        device: Target device for model
        args: Configuration arguments (must have model configuration attributes)
        
    Returns:
        Loaded model instance in evaluation mode, or None if loading fails
        
    Raises:
        FileNotFoundError: If checkpoint file doesn't exist
        RuntimeError: If checkpoint is incompatible with model architecture
        
    Examples:
        >>> model = load_checkpoint('DLinear', './checkpoints/.../checkpoint.pth', device, args)
        >>> if model is not None:
        ...     predictions = model(batch_x, itr=0)
        
    **Validates: Requirements 1.1, 1.2, 1.3, 1.4, 1.5, 2.4, 8.4**
    
    Implementation Notes:
        - Imports models locally to avoid circular dependencies
        - Sets model to eval() mode and disables gradient computation
        - Logs warnings for missing or corrupted checkpoints
        - Returns None on failure to enable graceful degradation
        - Llama2 is loaded on device directly in its __init__
    """
    try:
        # Import models locally to avoid issues
        from models.DLinear import DLinear
        from models.PatchTST import PatchTST
        from models.Llama2 import Llama2
        
        # Check if checkpoint exists
        if not os.path.exists(checkpoint_path):
            raise FileNotFoundError(f"Checkpoint file not found: {checkpoint_path}")
        
        logger.info(f"Loading {model_type} from {checkpoint_path}")
        
        # Instantiate model based on type
        if model_type == 'DLinear':
            model = DLinear(args, device)
            model.to(device)
        elif model_type == 'PatchTST':
            model = PatchTST(args, device)
            model.to(device)
        elif model_type == 'Llama2':
            # Llama2 handles device in __init__
            model = Llama2(args, device)
        else:
            logger.error(f"Unknown model type: {model_type}")
            return None
        
        # Load checkpoint state dict
        try:
            state_dict = torch.load(checkpoint_path, map_location=device)
            model.load_state_dict(state_dict, strict=False)
            logger.info(f"Successfully loaded {model_type} checkpoint")
        except Exception as e:
            logger.error(f"Failed to load state dict for {model_type}: {e}")
            return None
        
        # Set model to evaluation mode
        model.eval()
        
        # Disable gradient computation for inference
        for param in model.parameters():
            param.requires_grad = False
        
        logger.info(f"{model_type} ready for inference")
        
        return model
        
    except FileNotFoundError as e:
        logger.warning(f"Checkpoint file not found for {model_type}: {e}")
        return None
    except RuntimeError as e:
        logger.error(f"Failed to load {model_type} checkpoint (incompatible architecture): {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error loading {model_type} checkpoint: {e}")
        return None


