def validate_weights(weights: List[float], tolerance: float = WEIGHT_SUM_TOLERANCE) -> bool:
    """Validate that weights are non-negative and sum to 1.0 within tolerance.
    
    This function performs comprehensive validation of ensemble weights to ensure
    they form a valid probability distribution. It checks for negative values,
    zero sum (which cannot be normalized), and validates the sum is within
    acceptable tolerance of 1.0.
    
    Args:
        weights: List of weight values to validate
        tolerance: Acceptable deviation from sum of 1.0 (default: 0.001)
        
    Returns:
        True if weights are valid (non-negative and sum to 1.0 within tolerance)
        
    Raises:
        ValueError: If any weight is negative
        ValueError: If weights sum to zero (cannot be normalized)
        
    Examples:
        >>> validate_weights([0.3, 0.3, 0.4])  # Valid weights
        True
        
        >>> validate_weights([0.33, 0.33, 0.34])  # Valid, sum=1.0
        True
        
        >>> validate_weights([0.5, 0.5, 0.1])  # Invalid, sum=1.1
        False
        
        >>> validate_weights([0.3, -0.1, 0.8])  # Raises ValueError
        ValueError: Negative weights not allowed: weights must be non-negative floats
        
        >>> validate_weights([0.0, 0.0, 0.0])  # Raises ValueError
        ValueError: Weights sum to zero: cannot create valid probability distribution
        
    **Validates: Requirements 3.4, 9.3**
    
    Implementation Notes:
        - Negative weights are mathematically invalid for weighted averaging
        - Zero sum prevents normalization and indicates configuration error
        - Tolerance of 0.001 allows for floating-point rounding errors
        - This function is used by normalize_weights and EnsemblePredictor
    """
    # Check for negative weights first (critical error)
    if any(w < 0 for w in weights):
        raise ValueError(
            "Negative weights not allowed: weights must be non-negative floats"
        )
    
    # Calculate sum of weights
    weight_sum = sum(weights)
    
    # Check for zero sum (cannot be normalized)
    if weight_sum == 0.0:
        raise ValueError(
            "Weights sum to zero: cannot create valid probability distribution"
        )
    
    # Validate sum is within tolerance of 1.0
    return abs(weight_sum - 1.0) <= tolerance


def normalize_weights(weights: List[float]) -> List[float]:
    """Normalize weights to sum to 1.0.
    
    Computes normalized weights by dividing each weight by the sum of all weights.
    This ensures the resulting weights form a valid probability distribution.
    
    Args:
        weights: List of raw weight values (must be non-negative)
        
    Returns:
        Normalized weights summing to 1.0
        
    Raises:
        ValueError: If weights sum to zero (cannot normalize)
        ValueError: If any weight is negative
        
    Examples:
        >>> normalize_weights([0.3, 0.3, 0.6])
        [0.25, 0.25, 0.5]
        
        >>> normalize_weights([1.0, 2.0, 3.0])
        [0.1666..., 0.3333..., 0.5]
        
        >>> normalize_weights([0.0, 0.0, 0.0])  # Raises ValueError
        ValueError: Weights sum to zero, cannot normalize
        
    **Validates: Requirement 3.5**
    
    Implementation Notes:
        - Function is idempotent: normalize(normalize(w)) = normalize(w)
        - Used by adjust_weights_for_missing_models for weight rebalancing
        - Validates non-negative weights before normalization
    """
    # Validate non-negative weights
    if any(w < 0 for w in weights):
        raise ValueError("Cannot normalize weights: all weights must be non-negative")
    
    # Calculate sum of weights
    weight_sum = sum(weights)
    
    # Check for zero sum (cannot normalize)
    if weight_sum == 0.0:
        raise ValueError("Weights sum to zero, cannot normalize")
    
    # Normalize: divide each weight by sum
    normalized = [w / weight_sum for w in weights]
    
    return normalized


def adjust_weights_for_missing_models(
    original_weights: Dict[str, float],
    available_models: List[str]
) -> Dict[str, float]:
    """Adjust weights for missing models by filtering and normalizing.
    
    When some models are unavailable (checkpoints missing or failed to load),
    this function filters the weight dictionary to keep only available models,
    then normalizes the remaining weights to sum to 1.0. This enables graceful
    degradation where the ensemble continues with a subset of models.
    
    Args:
        original_weights: Dictionary mapping model names to original weights
        available_models: List of model names that were successfully loaded
        
    Returns:
        Adjusted weight dictionary with only available models, normalized to sum to 1.0
        
    Raises:
        ValueError: If no models are available (empty available_models list)
        ValueError: If all available model weights are zero
        
    Examples:
        >>> weights = {'DLinear': 0.3, 'PatchTST': 0.3, 'Llama2': 0.4}
        >>> available = ['DLinear', 'Llama2']  # PatchTST missing
        >>> adjust_weights_for_missing_models(weights, available)
        {'DLinear': 0.42857..., 'Llama2': 0.57142...}
        # Original 0.3 + 0.4 = 0.7, normalized: 0.3/0.7 ≈ 0.429, 0.4/0.7 ≈ 0.571
        
        >>> weights = {'DLinear': 0.3, 'PatchTST': 0.3, 'Llama2': 0.4}
        >>> available = ['Llama2']  # Only Llama2 available
        >>> adjust_weights_for_missing_models(weights, available)
        {'Llama2': 1.0}
        
        >>> weights = {'DLinear': 0.3, 'PatchTST': 0.3, 'Llama2': 0.4}
        >>> available = []  # No models available
        >>> adjust_weights_for_missing_models(weights, available)
        ValueError: No models available: cannot adjust weights for empty model set
        
    **Validates: Requirements 8.2, 8.5**
    
    Implementation Notes:
        - Logs missing models and adjusted weights for debugging
        - Handles edge case of single available model (weight = 1.0)
        - Used by EnsemblePredictor.load_checkpoints() for fallback handling
        - Preserves relative proportions of available model weights
        
    Logging Output:
        - INFO: Missing models and their original weights
        - INFO: Adjusted weights for available models
        - WARNING: If operating with reduced model set
    """
    # Validate we have at least one model available
    if not available_models:
        raise ValueError(
            "No models available: cannot adjust weights for empty model set. "
            "At least one model checkpoint must be successfully loaded."
        )
    
    # Identify missing models for logging
    missing_models = [model for model in original_weights.keys() 
                     if model not in available_models]
    
    # Log missing models if any
    if missing_models:
        missing_info = ', '.join([f"{model} (weight={original_weights[model]:.3f})" 
                                 for model in missing_models])
        logger.warning(f"Missing models: {missing_info}")
        logger.info(f"Adjusting weights for {len(available_models)} available model(s): "
                   f"{', '.join(available_models)}")
    
    # Filter weights to only available models
    filtered_weights = {model: original_weights[model] 
                       for model in available_models 
                       if model in original_weights}
    
    # Handle case where an available model wasn't in original weights
    # (shouldn't happen in normal operation, but handle gracefully)
    for model in available_models:
        if model not in filtered_weights:
            logger.warning(f"Available model '{model}' not in original weights, "
                         f"assigning equal weight")
            filtered_weights[model] = 1.0  # Will be normalized anyway
    
    # Extract weights for normalization
    model_names = list(filtered_weights.keys())
    weight_values = list(filtered_weights.values())
    
    # Check if all weights are zero (edge case)
    if sum(weight_values) == 0.0:
        raise ValueError(
            f"All available model weights sum to zero: {filtered_weights}. "
            f"Cannot create valid probability distribution."
        )
    
    # Normalize weights to sum to 1.0
    normalized_weights = normalize_weights(weight_values)
    
    # Create adjusted weight dictionary
    adjusted_weights = {model: weight 
                       for model, weight in zip(model_names, normalized_weights)}
    
    # Log adjusted weights
    adjusted_info = ', '.join([f"{model}={weight:.4f}" 
                              for model, weight in adjusted_weights.items()])
    logger.info(f"Adjusted weights (normalized): {adjusted_info}")
    
    # Verify sum is within tolerance (sanity check)
    weight_sum = sum(adjusted_weights.values())
    if abs(weight_sum - 1.0) > WEIGHT_SUM_TOLERANCE:
        logger.warning(f"Adjusted weights sum to {weight_sum:.6f}, expected 1.0")
    
    return adjusted_weights


