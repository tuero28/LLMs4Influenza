class EnsemblePredictor(nn.Module):
    """Hybrid ensemble predictor combining multiple model predictions.
    
    This class loads pre-trained checkpoints for DLinear, PatchTST, and Llama2
    models, generates predictions from each, and combines them using weighted
    averaging to achieve improved forecasting accuracy.
    
    The predictor uses sequential model loading and inference to minimize GPU
    memory usage, making it suitable for resource-constrained environments.
    
    Attributes:
        args: Configuration arguments
        device: Target device for computation
        models: Dictionary of loaded model instances {model_name: model}
        weights: Dictionary of ensemble weights {model_name: weight}
        config: EnsembleConfig instance
        
    Example:
        >>> predictor = EnsemblePredictor(args, device)
        >>> predictor.load_checkpoints()
        >>> predictions = predictor.forward(batch_x, iteration=0)
        
    **Validates: Requirements 1.1-1.5, 2.1-2.5, 3.1-3.5, 8.1-8.5**
    """
    
    def __init__(self, args, device: torch.device):
        """Initialize ensemble predictor.
        
        Args:
            args: Configuration arguments (must include ensemble_weights, checkpoints, etc.)
            device: Target device for computation
            
        **Validates: Requirements 3.1, 3.3, 9.1, 9.2**
        """
        super(EnsemblePredictor, self).__init__()
        
        self.args = args
        self.device = device
        self.models = {}  # Will be populated by load_checkpoints()
        
        # Parse ensemble weights from args
        if hasattr(args, 'ensemble_weights') and isinstance(args.ensemble_weights, str):
            # Parse from comma-separated string
            weight_list = parse_ensemble_weights(args.ensemble_weights)
            self.weights = {
                'DLinear': weight_list[0],
                'PatchTST': weight_list[1],
                'Llama2': weight_list[2]
            }
        elif hasattr(args, 'ensemble_weights') and isinstance(args.ensemble_weights, (list, tuple)):
            # Already a list
            self.weights = {
                'DLinear': args.ensemble_weights[0],
                'PatchTST': args.ensemble_weights[1],
                'Llama2': args.ensemble_weights[2]
            }
        else:
            # Use defaults
            self.weights = DEFAULT_WEIGHTS.copy()
        
        # Validate weights
        weight_values = list(self.weights.values())
        if not validate_weights(weight_values):
            logger.warning(f"Weights do not sum to 1.0, normalizing: {self.weights}")
            normalized = normalize_weights(weight_values)
            self.weights = {
                'DLinear': normalized[0],
                'PatchTST': normalized[1],
                'Llama2': normalized[2]
            }
        
        logger.info(f"Initialized EnsemblePredictor with weights: {self.weights}")
        logger.info(f"Device: {device}")
    
    def load_checkpoints(self, checkpoints_dir: str = './checkpoints/', iteration: int = 0):
        """Load model checkpoints from disk.
        
        Discovers and loads checkpoints for all three models (DLinear, PatchTST, Llama2).
        If some checkpoints are missing, adjusts weights for available models.
        
        Args:
            checkpoints_dir: Base directory containing checkpoints
            iteration: Training iteration number (0, 1, or 2)
            
        **Validates: Requirements 1.1, 1.2, 1.3, 1.4, 8.1, 8.3**
        """
        logger.info(f"Loading checkpoints from {checkpoints_dir} (iteration {iteration})")
        
        with Timer(logger, "Checkpoint loading"):
            # Discover checkpoint paths
            model_types = ['DLinear', 'PatchTST', 'Llama2']
            checkpoint_paths = discover_checkpoints(checkpoints_dir, model_types, iteration)
            
            # Load each checkpoint
            for model_type in model_types:
                if model_type in checkpoint_paths:
                    checkpoint_path = checkpoint_paths[model_type]
                    
                    # Load checkpoint
                    model = load_checkpoint(model_type, checkpoint_path, self.device, self.args)
                    
                    if model is not None:
                        self.models[model_type] = model
                        logger.info(f"✓ {model_type} loaded successfully")
                        
                        # Log GPU memory after loading
                        log_gpu_memory(logger, self.device, f"after loading {model_type}")
                    else:
                        logger.warning(f"✗ {model_type} failed to load")
                else:
                    logger.warning(f"✗ {model_type} checkpoint not found")
            
            # Adjust weights for available models
            available_models = list(self.models.keys())
            if len(available_models) < len(model_types):
                logger.warning(f"Only {len(available_models)}/{len(model_types)} models loaded")
                self.weights = adjust_weights_for_missing_models(self.weights, available_models)
            
            # Summary
            logger.info(f"Loaded {len(self.models)}/{len(model_types)} models: {', '.join(available_models)}")
            logger.info(f"Final ensemble weights: {self.weights}")
    
    def forward(self, batch_x: torch.Tensor, itr: int = 0) -> torch.Tensor:
        """Generate ensemble predictions using weighted averaging.
        
        Runs inference on each loaded model sequentially, clears GPU cache between
        models to minimize memory usage, then combines predictions using weighted averaging.
        
        Args:
            batch_x: Input tensor [batch_size, seq_len, features]
            itr: Iteration number (passed to model forward methods)
            
        Returns:
            Ensemble prediction tensor [batch_size, pred_len, features]
            
        Raises:
            RuntimeError: If no models are loaded
            
        **Validates: Requirements 2.1, 2.2, 2.3, 2.4, 2.5, 3.2, 11.1, 11.2, 11.5**
        """
        if len(self.models) == 0:
            raise RuntimeError("No models loaded. Call load_checkpoints() first.")
        
        predictions = {}
        model_weights = []
        
        # Generate predictions from each model sequentially
        for model_name, model in self.models.items():
            logger.debug(f"Generating predictions from {model_name}")
            
            # Move model to device (may already be there)
            model.to(self.device)
            model.eval()
            
            # Run inference
            with torch.no_grad():
                pred = model(batch_x, itr)
            
            # Store prediction
            predictions[model_name] = pred
            model_weights.append(self.weights[model_name])
            
            # Clear GPU cache to free memory
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            
            logger.debug(f"{model_name} prediction shape: {pred.shape}")
        
        # Combine predictions using weighted averaging
        prediction_list = [predictions[name] for name in self.models.keys()]
        ensemble_prediction = weighted_average(prediction_list, model_weights)
        
        logger.debug(f"Ensemble prediction shape: {ensemble_prediction.shape}")
        
        return ensemble_prediction


